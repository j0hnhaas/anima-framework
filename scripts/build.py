"""Build the navigator from the ANIMA source files.

Writes
    data/navigator.json        all sources and requirements (machine-readable)
    data/navigator.csv         one row per requirement
    navigator/requirements.md  human-readable table with coverage of the triad
    search/flow.md             flow of documents through the search (PRISMA-ScR)

Run scripts/validate.py first. With --check, nothing is written; the script
exits with status 1 if the generated files are not up to date.

Usage:
    python scripts/build.py
    python scripts/build.py --check
"""

from __future__ import annotations

import argparse
import csv
import io
import json
import sys
from collections import Counter
from pathlib import Path

from common import EDGES, FLOWS, ROOT, SEARCH_DIR, SOURCES_DIR, read_front_matter, source_files

OUT_JSON = ROOT / "data" / "navigator.json"
OUT_CSV = ROOT / "data" / "navigator.csv"
OUT_MD = ROOT / "navigator" / "requirements.md"
OUT_FLOW = SEARCH_DIR / "flow.md"

EXCLUSION_REASONS = {
    "E1": "topic", "E2": "profession out of scope", "E3": "issuer", "E4": "not current",
    "E5": "duplicate", "E6": "no requirement", "E7": "not accessible", "E8": "language",
}

SOURCE_FIELDS = ["id", "short_title", "title", "issuer", "pillar", "jurisdiction", "bindingness", "reference", "url", "checked", "status"]
CSV_FIELDS = ["id", "requirement", "source_id", "source", "reference", "pillar", "jurisdiction", "bindingness",
              "edge", "flow", "configuration", "addressee", "topic", "spectrum", "status", "note"]

CONFIG_NAMES = {
    1: "full triad, open",
    2: "practitioner-supported",
    3: "client alone with the AI",
    4: "client uses AI covertly",
    5: "practitioner uses AI covertly",
    6: "no direct client contact",
}


def collect() -> tuple[list[dict], list[dict]]:
    sources, requirements = [], []
    for path in source_files(SOURCES_DIR):
        data = read_front_matter(path)
        source = {field: data.get(field, "") for field in SOURCE_FIELDS}
        source["file"] = path.relative_to(ROOT).as_posix()
        sources.append(source)
        for req in data.get("requirements") or []:
            requirements.append({
                "id": req["id"],
                "requirement": req["requirement"],
                "source_id": data["id"],
                "source": data["short_title"],
                "reference": req["reference"],
                "pillar": data["pillar"],
                "jurisdiction": data["jurisdiction"],
                "bindingness": data["bindingness"],
                "edge": req["edge"],
                "flow": req["flow"],
                "configuration": req["configuration"],
                "addressee": req["addressee"],
                "topic": req["topic"],
                "spectrum": req["spectrum"],
                "status": data["status"],
                "note": req.get("note", ""),
            })
    sources.sort(key=lambda s: s["id"])
    requirements.sort(key=lambda r: r["id"])
    return sources, requirements


def render_json(sources: list[dict], requirements: list[dict]) -> str:
    payload = {
        "description": "ANIMA navigator: all requirements mapped onto the triad. Generated by scripts/build.py.",
        "license": "CC0-1.0",
        "sources": sources,
        "requirements": requirements,
    }
    return json.dumps(payload, ensure_ascii=False, indent=2) + "\n"


def render_csv(requirements: list[dict]) -> str:
    buffer = io.StringIO()
    writer = csv.DictWriter(buffer, fieldnames=CSV_FIELDS, lineterminator="\n")
    writer.writeheader()
    for req in requirements:
        row = {k: ("; ".join(str(v) for v in req[k]) if isinstance(req[k], list) else req[k]) for k in CSV_FIELDS}
        writer.writerow(row)
    return buffer.getvalue()


def cell(text: object) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def render_markdown(sources: list[dict], requirements: list[dict]) -> str:
    lines = [
        "---",
        "title: Requirements",
        "---",
        "",
        "# Requirements",
        "",
        "*This page is generated by `scripts/build.py` from the source files. Do not edit it by hand.*",
        "",
    ]
    if not requirements:
        lines += ["No requirements have been added yet.", ""]
        return "\n".join(lines)

    lines += [f"**{len(requirements)}** requirement(s) from **{len(sources)}** source(s). "
              "Content with status `draft` has not yet been reviewed by a second person.", ""]

    lines += ["## All requirements", "",
              "| ID | Requirement | Source | Edge | Flow | Config. | Addressee | Status |",
              "|---|---|---|---|---|---|---|---|"]
    for r in requirements:
        lines.append(
            f"| {r['id']} | {cell(r['requirement'])} | {cell(r['source'])}, {cell(r['reference'])} "
            f"| {', '.join(r['edge'])} | {', '.join(r['flow'])} | {', '.join(str(c) for c in r['configuration'])} "
            f"| {r['addressee']} | {r['status']} |"
        )

    lines += ["", "## Coverage of the triad", "",
              "Number of requirements per edge and flow. A **0** marks a gap: no source assigns a duty there.", "",
              "| Edge | " + " | ".join(FLOWS) + " |",
              "|---|" + "---|" * len(FLOWS)]
    for edge in EDGES:
        counts = [sum(1 for r in requirements if edge in r["edge"] and flow in r["flow"]) for flow in FLOWS]
        lines.append(f"| {edge} | " + " | ".join(f"**{c}**" if c == 0 else str(c) for c in counts) + " |")

    lines += ["", "## Coverage by configuration", "",
              "| Configuration | Requirements |", "|---|---|"]
    for number, name in CONFIG_NAMES.items():
        count = sum(1 for r in requirements if number in r["configuration"])
        lines.append(f"| {number} – {name} | {f'**{count}**' if count == 0 else count} |")

    lines.append("")
    return "\n".join(lines)


def render_flow() -> str:
    """Flow of documents through the search, following the PRISMA-ScR flow diagram."""
    path = SEARCH_DIR / "candidates.csv"
    rows = list(csv.DictReader(path.open(encoding="utf-8", newline=""))) if path.exists() else []
    log_path = SEARCH_DIR / "search-log.csv"
    searches = list(csv.DictReader(log_path.open(encoding="utf-8", newline=""))) if log_path.exists() else []

    via = Counter(r["identified_via"] for r in rows)
    title = Counter(r["title_screening"] for r in rows)
    full = Counter(r["full_text_screening"] for r in rows if r["title_screening"] in {"include", "unclear"})
    reasons_title = Counter(r["exclusion_reason"] for r in rows if r["title_screening"] == "exclude")
    reasons_full = Counter(r["exclusion_reason"] for r in rows if r["full_text_screening"] == "exclude")
    with_file = sum(1 for r in rows if r["source_id"])
    screened_title = len(rows) - title["pending"]
    assessed_full = sum(full[k] for k in ("include", "exclude", "unclear"))

    def reasons(counter: Counter) -> list[str]:
        return [f"  - {code} {EXCLUSION_REASONS[code]}: {counter[code]}" for code in sorted(counter) if code]

    lines = [
        "---", "title: Search flow", "---", "",
        "# Search flow", "",
        "*This page is generated by `scripts/build.py` from [candidates.csv](candidates.csv) and "
        "[search-log.csv](search-log.csv). Do not edit it by hand.* "
        "The stages follow the flow diagram of PRISMA-ScR (see the [search protocol](../docs/search-protocol.md)).", "",
        f"Searches recorded: **{len(searches)}**", "",
        "## Identification", "",
        f"- Documents identified: **{len(rows)}**",
    ]
    lines += [f"  - {k}: {via[k]}" for k in sorted(via)]
    lines += ["", "## Screening of titles and summaries", "",
              f"- Screened: **{screened_title}** · pending: {title['pending']}",
              f"- Excluded: **{title['exclude']}**"]
    lines += reasons(reasons_title)
    lines += [f"- Passed to full-text screening: {title['include'] + title['unclear']}",
              "", "## Screening of full texts", "",
              f"- Assessed: **{assessed_full}** · pending: {full['pending']}",
              f"- Excluded: **{full['exclude']}**"]
    lines += reasons(reasons_full)
    lines += [f"- Unclear, to be resolved: {full['unclear']}",
              "", "## Included", "",
              f"- Documents included: **{full['include']}**",
              f"- Of which with a source file in `sources/`: {with_file}", ""]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="only check that the generated files are up to date")
    args = parser.parse_args()

    sources, requirements = collect()
    outputs = {
        OUT_JSON: render_json(sources, requirements),
        OUT_CSV: render_csv(requirements),
        OUT_MD: render_markdown(sources, requirements),
        OUT_FLOW: render_flow(),
    }

    if args.check:
        stale = [p for p, content in outputs.items() if not p.exists() or p.read_text(encoding="utf-8") != content]
        if stale:
            print("Generated files are not up to date. Run: python scripts/build.py")
            for p in stale:
                print(f"  - {p.relative_to(ROOT)}")
            return 1
        print("Generated files are up to date.")
        return 0

    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"Wrote {path.relative_to(ROOT)}")
    print(f"{len(requirements)} requirement(s) from {len(sources)} source(s).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
